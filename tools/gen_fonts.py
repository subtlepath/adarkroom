#!/usr/bin/env python3
"""gen_fonts.py — the bitmap strikes the firmware sets its type in, as C++ tables.

Times (the web game's own face: css/main.css asks for "Times New Roman", Times) from the Adobe
X11 100 dpi strikes, and UW ttyp0 (a monospace for the map and the ascent into space), both read
unmodified from their BDF files under fonts/. Only the characters the game can show are
kept: printable ASCII, Latin-1, typographic quotes and dashes, arrows and a few shapes.

    python3 tools/gen_fonts.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "src", "generated", "fonts_data.cpp")

# (C++ id, file). The ids are FontId in src/core/fonts.h, in this order. Times 18 at 100 dpi (25 px;
# CrossPoint's Times 12) is the body and the least the game sets in, save a longer caption, which may
# take Times italic 14 (20 px).
STRIKES = [
    ("F_R25", "x11/timR18.bdf"),
    ("F_R34", "x11/timR24.bdf"),
    ("F_I20", "x11/timI14.bdf"),
    ("F_I25", "x11/timI18.bdf"),
    ("F_B25", "x11/timB18.bdf"),
    ("F_B34", "x11/timB24.bdf"),
    ("F_M22", "ttyp0/t0-22-uni.bdf"),
    ("F_MB22", "ttyp0/t0-22b-uni.bdf"),
    ("F_MB30", "ttyp0/t0-30b-uni.bdf"),
]

WANTED = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | {
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2032,
    0x2190, 0x2191, 0x2192, 0x2193, 0x2195, 0x2194,
    0x25A0, 0x25A1, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25CF, 0x25CB, 0x2588, 0x2591, 0x2592, 0x2593,
}


def parse_bdf(path):
    props = {}
    glyphs = {}
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("STARTCHAR"):
            enc = None
            dw = 0
            bbx = (0, 0, 0, 0)
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                p = lines[i].split()
                if p[0] == "ENCODING":
                    enc = int(p[1])
                elif p[0] == "DWIDTH":
                    dw = int(p[1])
                elif p[0] == "BBX":
                    bbx = tuple(int(x) for x in p[1:5])
                elif p[0] == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    break
                i += 1
            if enc is not None and enc in WANTED:
                glyphs[enc] = (dw, bbx, rows)
        else:
            p = ln.split()
            if p and p[0] in ("FONT_ASCENT", "FONT_DESCENT", "PIXEL_SIZE"):
                props[p[0]] = int(p[1])
        i += 1
    return props, glyphs


def main():
    out = []
    w = out.append
    w("// Generated by tools/gen_fonts.py from fonts/ (BDF). Do not edit.")
    w("//")
    w("// Times: Copyright 1984-1989, 1994 Adobe Systems Incorporated. Copyright 1988, 1994 Digital")
    w("// Equipment Corporation. (fonts/x11/COPYING-Adobe.) UW ttyp0: Copyright (C) 2012-2025 Uwe")
    w("// Waldmann (fonts/ttyp0/LICENSE).")
    w('#include "../core/fonts.h"')
    w("")
    w("namespace adr {")
    w("")
    table = []
    total = 0
    for cid, rel in STRIKES:
        props, glyphs = parse_bdf(os.path.join(ROOT, "fonts", rel))
        cps = sorted(glyphs)
        bitmap = bytearray()
        recs = []
        for cp in cps:
            dw, (bw, bh, bx, by), rows = glyphs[cp]
            stride = (bw + 7) // 8
            off = len(bitmap)
            for r in rows[:bh]:
                raw = bytes.fromhex(r)
                bitmap += raw[:stride].ljust(stride, b"\0")
            recs.append((off, bw, bh, bx, by + bh, dw))
        name = cid[2:]
        w(f"static const uint16_t kCp{name}[] = {{{', '.join(str(c) for c in cps)}}};")
        w(f"static const GlyphRec kGl{name}[] = {{")
        for off, bw, bh, bx, top, dw in recs:
            w(f"  {{{off}, {bw}, {bh}, {bx}, {top}, {dw}}},")
        w("};")
        w(f"static const uint8_t kBm{name}[] = {{")
        for k in range(0, len(bitmap), 24):
            w("  " + ", ".join(str(b) for b in bitmap[k:k + 24]) + ",")
        w("};")
        sp = glyphs.get(0x20, (props["PIXEL_SIZE"] // 3, None, None))[0]
        table.append(f"  {{{props['FONT_ASCENT']}, {props['FONT_DESCENT']}, {props['PIXEL_SIZE']}, {sp}, "
                     f"{len(cps)}, kCp{name}, kGl{name}, kBm{name}}},  // {cid} {rel}")
        total += len(bitmap) + len(cps) * 10
    w("")
    w("const FontData kFonts[F_COUNT] = {")
    out.extend(table)
    w("};")
    w("")
    w("}  // namespace adr")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(STRIKES)} strikes, {total // 1024} KiB -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    sys.exit(main())
